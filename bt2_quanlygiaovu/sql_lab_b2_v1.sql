CREATE TABLE KHOA (
	MAKHOA VARCHAR(4) PRIMARY KEY,
	TENKHOA VARCHAR(40),
	NGTLAP DATE,
	TRGKHOA CHAR(4)
);

CREATE TABLE MONHOC (
	MAMH VARCHAR(10) PRIMARY KEY,
	TENMH VARCHAR(40),
	TCLT SMALLINT,
	TCTH SMALLINT,
	MAKHOA VARCHAR(4),
	
	CONSTRAINT FK_MONHOC_KHOA 
		FOREIGN KEY (MAKHOA) 
		REFERENCES KHOA(MAKHOA)
);

CREATE TABLE DIEUKIEN (
    MAMH VARCHAR(10),
    MAMH_TRUOC VARCHAR(10),

    PRIMARY KEY (MAMH, MAMH_TRUOC),

    CONSTRAINT FK_DIEUKIEN_MONHOC
        FOREIGN KEY (MAMH)
        REFERENCES MONHOC(MAMH),

    CONSTRAINT FK_DIEUKIEN_MONHOC_TRUOC
        FOREIGN KEY (MAMH_TRUOC)
        REFERENCES MONHOC(MAMH),
);

CREATE TABLE GIAOVIEN (
    MAGV CHAR(4) PRIMARY KEY,
    HOTEN VARCHAR(40),
    HOCVI VARCHAR(10),
    HOCHAM VARCHAR(10),
    GIOITINH VARCHAR(3),
    NGSINH DATE,
    NGVL DATE,
    HESO NUMERIC(4,2),
    MUCLUONG NUMERIC(19,4),
    MAKHOA VARCHAR(4),

    CONSTRAINT FK_GIAOVIEN_KHOA
        FOREIGN KEY (MAKHOA)
        REFERENCES KHOA(MAKHOA)
);

ALTER TABLE KHOA
ADD CONSTRAINT FK_KHOA_GIAOVIEN
FOREIGN KEY (TRGKHOA)
REFERENCES GIAOVIEN(MAGV);

CREATE TABLE LOP (
    MALOP CHAR(3) PRIMARY KEY,
    TENLOP VARCHAR(40),
    TRGLOP CHAR(5),
    SISO SMALLINT CHECK (SISO BETWEEN 0 AND 255),
    MAGVCN CHAR(4),

    CONSTRAINT FK_LOP_GIAOVIEN
        FOREIGN KEY (MAGVCN)
        REFERENCES GIAOVIEN(MAGV)
);

CREATE TABLE HOCVIEN (
    MAHV CHAR(5) PRIMARY KEY,
    HO VARCHAR(40),
    TEN VARCHAR(10),
    NGSINH DATE,
    GIOITINH VARCHAR(3),
    NOISINH VARCHAR(40),
    MALOP CHAR(3),

    CONSTRAINT FK_HOCVIEN_LOP
        FOREIGN KEY (MALOP)
        REFERENCES LOP(MALOP)
);

ALTER TABLE LOP
ADD CONSTRAINT FK_LOP_HOCVIEN
FOREIGN KEY (TRGLOP)
REFERENCES HOCVIEN(MAHV);

CREATE TABLE GIANGDAY (
    MALOP CHAR(3),
    MAMH VARCHAR(10),
    MAGV CHAR(4),
    HOCKY SMALLINT CHECK (HOCKY BETWEEN 0 AND 255),
    NAM SMALLINT,
    TUNGAY DATE,
    DENNGAY DATE,

    PRIMARY KEY (MALOP, MAMH, HOCKY, NAM),

    CONSTRAINT FK_GIANGDAY_LOP
        FOREIGN KEY (MALOP)
        REFERENCES LOP(MALOP),

    CONSTRAINT FK_GIANGDAY_MONHOC
        FOREIGN KEY (MAMH)
        REFERENCES MONHOC(MAMH),

    CONSTRAINT FK_GIANGDAY_GIAOVIEN
        FOREIGN KEY (MAGV)
        REFERENCES GIAOVIEN(MAGV),

    CONSTRAINT CHK_GIANGDAY_DATE
        CHECK (DENNGAY IS NULL OR TUNGAY IS NULL OR DENNGAY >= TUNGAY)
);


CREATE TABLE KETQUATHI (
    MAHV CHAR(5),
    MAMH VARCHAR(10),
    LANTHI SMALLINT CHECK (LANTHI BETWEEN 0 AND 255),
    NGTHI DATE,
    DIEM NUMERIC(4,2),
    KQUA VARCHAR(10),

    PRIMARY KEY (MAHV, MAMH, LANTHI),

    CONSTRAINT FK_KETQUATHI_HOCVIEN
        FOREIGN KEY (MAHV)
        REFERENCES HOCVIEN(MAHV),

    CONSTRAINT FK_KETQUATHI_MONHOC
        FOREIGN KEY (MAMH)
        REFERENCES MONHOC(MAMH),

    CONSTRAINT CHK_KETQUATHI_DIEM
        CHECK (DIEM BETWEEN 0 AND 10)
);
